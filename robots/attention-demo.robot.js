import { test, expect } from '@playwright/test'
import { teacherLogin } from './lib/teacher.js'

test('Varierad fokusdemo visar 20 testelever, hastighet, fel och tidsmönster', async ({ page, request }, testInfo) => {
  const demo = await (await request.post('/__robot/attention-demo', { data: {} })).json()
  expect(demo.ok).toBe(true); expect(demo.count).toBe(1500)
  await teacherLogin(page, { ...demo.teacher, attentionFixtureClassIds: [demo.classId] })
  await page.getByRole('button', { name: /^Fokusövningar/ }).click()
  const panel = page.getByRole('region', { name: 'Fokusövningar', exact: true })
  await expect(panel.getByRole('status')).toHaveText('20 av 20 elever hämtade', { timeout: 30000 })
  await page.setViewportSize({ width: 1440, height: 1100 })
  await panel.getByRole('button', { name: 'Dagsform', exact: true }).click()
  const form = panel.getByRole('region', { name: 'Dagsform för klassen' })
  await expect(form).toContainText('Robot 13 Snabb rätt')
  await form.screenshot({ path: testInfo.outputPath('demo-matris.png') })
  await panel.getByRole('combobox', { name: 'Övning för fokusdiagram' }).selectOption('discover')
  await form.getByRole('button', { name: 'Fyrfältare', exact: true }).click()
  await form.screenshot({ path: testInfo.outputPath('demo-fokus.png') })
  await panel.getByRole('combobox', { name: 'Övning för fokusdiagram' }).selectOption('choose')
  await form.getByRole('combobox', { name: 'Fyrfältarens vertikala axel' }).selectOption('task')
  await form.screenshot({ path: testInfo.outputPath('demo-kontroll.png') })
  await panel.getByRole('combobox', { name: 'Övning för fokusdiagram' }).selectOption('multi')
  await form.screenshot({ path: testInfo.outputPath('demo-multi.png') })
  await panel.getByRole('combobox', { name: 'Elev i fokusmodulen' }).selectOption(demo.pupils[19].studentId)
  await panel.getByRole('combobox', { name: 'Övning för fokusdiagram' }).selectOption('discover')
  await panel.getByRole('button', { name: 'Veckomönster', exact: true }).click()
  await panel.getByRole('region', { name: 'Elevens veckomönster' }).screenshot({ path: testInfo.outputPath('demo-veckomönster.png') })
  await panel.getByRole('combobox', { name: 'Elev i fokusmodulen' }).selectOption(demo.pupils[18].studentId)
  await panel.getByRole('region', { name: 'Individens fokusresultat' }).screenshot({ path: testInfo.outputPath('demo-uthållighet.png') })
})
