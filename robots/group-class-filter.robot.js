import { test, expect } from '@playwright/test'
import { createPupil } from './lib/app.js'
import { createTeacher, teacherLogin } from './lib/teacher.js'

test('Group members can be chosen across class filters without losing selections', async ({ page, request }, testInfo) => {
  const tag = Math.random().toString(36).slice(2, 8)
  const classes = ['A', 'B', 'C'].map(letter => ({ id: `group-${tag}-${letter}`, name: `Klass ${letter} ${tag}` }))
  const names = ['Anna', 'Bertil', 'Cecilia'].map(name => `${name} ${tag}`)
  for (const [index, record] of classes.entries()) {
    await createPupil(request, { name: names[index], classId: record.id, className: record.name })
  }
  const teacher = await createTeacher(request, { classIds: classes.map(record => record.id) })
  await teacherLogin(page, teacher)
  await page.getByRole('button', { name: /^Administration(?:\s|$)/ }).click()
  await page.getByRole('button', { name: '+ Ny grupp', exact: true }).click()
  const panel = page.locator('[data-open-item]')
  const pupil = index => panel.getByRole('checkbox', { name: names[index], exact: true })
  const klass = index => panel.getByRole('checkbox', { name: classes[index].name, exact: true })
  await panel.getByRole('textbox', { name: 'Gruppnamn' }).fill(`Urval ${tag}`)
  await klass(0).check()
  await expect(pupil(0)).toBeVisible()
  await expect(pupil(1)).toHaveCount(0)
  await pupil(0).check()
  await klass(1).check()
  await expect(pupil(0)).toBeChecked()
  await expect(pupil(1)).toBeVisible()
  await expect(pupil(2)).toHaveCount(0)
  await pupil(1).check()
  await klass(0).uncheck()
  await expect(panel.getByText('Elever (2 valda)', { exact: true })).toBeVisible()
  await expect(panel.getByText('1 valda elever är dolda av filtret. De är fortfarande med i gruppen.')).toBeVisible()
  await expect(pupil(1)).toBeChecked()
  await panel.getByRole('searchbox').fill(names[0])
  await expect(panel.getByText('Inga elever matchar filtret.')).toBeVisible()
  await panel.getByRole('searchbox').fill('')
  await klass(0).check()
  await expect(pupil(0)).toBeChecked()
  await expect(pupil(1)).toBeChecked()
  await panel.screenshot({ path: testInfo.outputPath('group-class-filter.png') })
  await klass(0).uncheck()
  await klass(1).uncheck()
  await expect(pupil(2)).toBeVisible()
  await expect(pupil(0)).toBeChecked()
  await expect(pupil(1)).toBeChecked()
  await expect(panel.getByRole('button', { name: 'Skapa grupp', exact: true })).toBeEnabled()
})
