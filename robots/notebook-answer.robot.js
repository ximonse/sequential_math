import { test, expect } from '@playwright/test'
import { createPupil, login, readServerProfile } from './lib/app.js'
import { createTeacher, openTab, teacherLogin } from './lib/teacher.js'

test('A pupil saves symbolic answers with and without a grid and the teacher receives the originals', async ({ page, request, browser }) => {
  const tag = Math.random().toString(36).slice(2, 8)
  const classId = `answer-${tag}`
  const pupil = await createPupil(request, { name: 'Answer Pupil', classId })
  const teacher = await createTeacher(request, { classIds: [classId], role: 'super_admin' })
  await teacherLogin(page, teacher)
  await page.evaluate(async data => {
    const response = await fetch('/api/teacher-diagnostic-assignments', { method: 'POST',
      headers: { 'Content-Type': 'application/json', 'x-teacher-token': sessionStorage.getItem('mathapp_teacher_api_token') },
      body: JSON.stringify(data) })
    if (!response.ok) throw new Error(`Could not create screening: ${response.status}`)
  }, { classId, studentIds: [pupil.studentId], titleSv: 'Svar med tecken',
    taskIds: ['add-carry-001', 'sub-through-zero-001'], itemOptions: { 'sub-through-zero-001': { gridEnabled: false } } })
  const context = await browser.newContext({ viewport: { width: 820, height: 1180 }, hasTouch: true })
  const student = await context.newPage()
  await login(student, pupil)
  await student.getByRole('button', { name: 'Svar med tecken', exact: true }).click()
  const answer = student.getByRole('textbox', { name: 'Mitt svar', exact: true })
  await answer.tap()
  await student.getByRole('button', { name: 'Skriv −', exact: true }).tap()
  await student.keyboard.type('25%')
  await expect(answer).toHaveValue('−25%')
  await expect(student.getByText('Alla skickade ändringar är sparade på servern.')).toBeVisible()
  await student.reload()
  await expect(answer).toHaveValue('−25%')
  await student.getByRole('button', { name: 'Nästa fråga', exact: true }).click()
  await expect(student.locator('.diagnostic-grid')).not.toBeVisible()
  await answer.tap()
  await student.getByRole('button', { name: 'Skriv −', exact: true }).tap()
  await student.keyboard.type('25')
  await student.getByRole('button', { name: /Fler tecken/ }).tap()
  await student.getByRole('button', { name: 'Skriv %', exact: true }).tap()
  await expect(answer).toHaveValue('−25%')
  await expect(student.getByText('Alla skickade ändringar är sparade på servern.')).toBeVisible()
  await student.reload()
  await expect(answer).toHaveValue('−25%')
  await student.getByRole('button', { name: 'Lämna in svaren', exact: true }).click()
  await expect(student).toHaveURL(new RegExp(`/student/${pupil.studentId}$`))
  await openTab(page, 'Screening')
  const panel = page.getByRole('heading', { name: 'Screening till elev eller klass' }).locator('..')
  await panel.getByRole('combobox', { name: 'Klass', exact: true }).selectOption(classId)
  await panel.getByRole('combobox', { name: 'Elev', exact: true }).selectOption(pupil.studentId)
  const evidence = panel.getByRole('region', { name: 'Diagnostiskt elevunderlag' })
  const buttons = panel.getByRole('button', { name: 'Visa underlag', exact: true })
  await expect(buttons).toHaveCount(2)
  for (const button of await buttons.all()) {
    await button.click()
    await expect(evidence.getByText(/^Slutsvar: −25%/)).toBeVisible()
  }
  expect((await readServerProfile(request, pupil.studentId)).problemLog).toEqual([])
  await context.close()
})

test('All notebook math keys stay in the active answer and leave grid notes untouched', async ({ page }, testInfo) => {
  await page.goto('/')
  await page.evaluate(() => {
    sessionStorage.setItem('mathapp_teacher_auth', '1')
    sessionStorage.setItem('mathapp_teacher_identity', JSON.stringify({
      teacherId: 'robot-admin', displayName: 'Robot', classIds: [], role: 'super_admin'
    }))
  })
  await page.goto('/teacher/ncm/diagnostic-grid')
  const answer = page.getByRole('textbox', { name: 'Mitt svar', exact: true })
  const key = character => page.getByRole('button', { name: `Skriv ${character}`, exact: true })
  const gridInput = page.locator('input[data-cell="0:0"]')
  await answer.tap()
  await key('−').tap()
  await key('2').tap()
  await key('5').tap()
  await expect(answer).toHaveValue('−25')
  await expect(page.locator('.diagnostic-cell--selected')).toHaveCount(0)
  await expect(page.locator('.notebook-answer-field')).toHaveAttribute('data-active', 'true')
  await expect(page.getByText('Mitt svar · aktivt', { exact: true })).toHaveCount(0)
  await expect(gridInput).toHaveAttribute('aria-label', /tom/)
  await page.getByRole('button', { name: /Fler tecken/ }).tap()
  await key('%').tap()
  await expect(answer).toHaveValue('−25%')
  await expect(page.locator('.notebook-answer-field')).toHaveAttribute('data-active', 'true')
  await page.getByRole('button', { name: 'Rensa', exact: true }).tap()
  await answer.press('2')
  await answer.press('/')
  await answer.press('5')
  await expect(answer).toHaveValue('2/5')
  const signs = ['−', '×', '/', '+', 'x', 'y', 'a', 'b', '=', '²', '%', '÷', '(', ')', 'n', 'c']
  await page.getByRole('button', { name: 'Rensa', exact: true }).tap()
  for (const sign of signs) {
    await key(sign).tap()
    await expect(answer).toBeFocused()
  }
  await expect(answer).toHaveValue(signs.join(''))
  await page.getByRole('button', { name: /Fler tecken/ }).tap()
  // Grid-specific note restrictions must not disable the answer's symbols.
  await gridInput.click()
  await gridInput.press('n')
  await gridInput.press('1')
  await answer.tap()
  await page.getByRole('button', { name: 'Rensa', exact: true }).tap()
  await key('−').tap()
  await key('2').tap()
  await key(',').tap()
  await key('5').tap()
  await page.getByRole('button', { name: /Fler tecken/ }).tap()
  await key('%').tap()
  await page.getByRole('button', { name: /Fler tecken/ }).tap()
  await expect(answer).toHaveValue('−2,5%')
  await expect(gridInput).toHaveAttribute('aria-label', /minnessiffra 1/)
  for (const theme of ['light', 'dark', 'dark-lime', 'psychedelic', 'real-psycadelic']) {
    await page.getByRole('combobox', { name: 'Välj tema' }).selectOption(theme)
    await expect(answer).toHaveCSS('background-color', 'rgb(255, 255, 255)')
    await expect(answer).toHaveCSS('color', 'rgb(22, 35, 50)')
    await page.screenshot({ path: testInfo.outputPath(`answer-active-${theme}.png`), fullPage: true })
  }
  await page.getByRole('button', { name: 'Visa JSON' }).click()
  await page.getByRole('button', { name: 'Återläs JSON' }).click()
  await expect(answer).toHaveValue('−2,5%')
  await gridInput.click()
  await gridInput.press('Escape')
  await key('+').tap()
  await expect(gridInput).toHaveAttribute('aria-label', /stor siffra \+/)
  await expect(answer).toHaveValue('−2,5%')
  await expect(page.locator('.notebook-answer-field')).toHaveAttribute('data-active', 'false')
})
