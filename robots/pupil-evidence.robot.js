import { test, expect } from '@playwright/test'
import { answerText, createPupil, fillAnswer, login, next, openOtherTraining, readServerProfile, submit, waitForTask } from './lib/app.js'
import { createTeacher } from './lib/teacher.js'
import { stockholmDay } from '../src/lib/evidencePeriod.js'

test('A teacher reads one pupil’s real saved answers with stable evidence pages and guarded detail', async ({ page, request }) => {
  const classId = `evidence-${Math.random().toString(36).slice(2, 8)}`
  const pupil = await createPupil(request, { classId, operations: ['subtraction'] })
  await login(page, pupil)
  await openOtherTraining(page)
  await page.getByRole('button', { name: /^Subtraktion/ }).click()
  for (let i = 0; i < 2; i++) {
    const { state } = await waitForTask(page)
    const correct = answerText(state.problem)
    await fillAnswer(page, i === 0 ? correct : String(Number(correct.replace(',', '.')) + 1))
    await submit(page)
    if (i === 0) await next(page)
  }
  await expect.poll(async () => (await readServerProfile(request, pupil.studentId)).problemLog.length).toBeGreaterThanOrEqual(2)
  const teacher = await createTeacher(request, { classIds: [classId] })
  const day = stockholmDay()
  const params = new URLSearchParams({ resource: 'evidence', classId, from: day, to: day, limit: '1' })
  const url = `/api/teacher-students/${pupil.studentId}`
  expect((await request.get(`${url}?${params}`)).status()).toBe(401)
  const { token } = await (await request.post('/api/teacher-login', { data: teacher })).json()
  const headers = { 'x-teacher-token': token }
  const first = await (await request.get(`${url}?${params}`, { headers })).json()
  expect(first.total).toBe(2)
  expect(first.coverage.practice.completeness).toBe('unknown')
  expect(first.entries[0].answer.status).toBe('correct')
  expect(JSON.stringify(first)).not.toMatch(/passwordHash|passwordSalt|masteryFacts/u)
  params.set('cursor', first.nextCursor)
  params.set('snapshotRevision', first.snapshotRevision)
  const second = await (await request.get(`${url}?${params}`, { headers })).json()
  expect(second.entries[0].answer.status).toBe('incorrect')
  expect(second.entries[0].ref).not.toBe(first.entries[0].ref)
  params.delete('cursor')
  params.set('ref', second.entries[0].ref)
  const detail = await (await request.get(`${url}?${params}`, { headers })).json()
  expect(detail.entry).toEqual(second.entries[0])
  params.set('snapshotRevision', 'stale')
  expect((await request.get(`${url}?${params}`, { headers })).status()).toBe(409)
  params.delete('ref'); params.delete('snapshotRevision'); params.set('source', 'screening')
  expect((await request.get(`${url}?${params}`, { headers })).status()).toBe(403)
  const stranger = await createTeacher(request, { classIds: [] })
  const other = await (await request.post('/api/teacher-login', { data: stranger })).json()
  params.set('source', 'practice')
  expect((await request.get(`${url}?${params}`, { headers: { 'x-teacher-token': other.token } })).status()).toBe(403)
})

test('Screening evidence exposes the frozen subtraction and unchanged notebook original only on detail read', async ({ page, request }) => {
  const classId = `evidence-work-${Math.random().toString(36).slice(2, 8)}`
  const pupil = await createPupil(request, { classId, name: 'Evidence Work' })
  const teacher = await createTeacher(request, { classIds: [classId], role: 'super_admin' })
  const { token } = await (await request.post('/api/teacher-login', { data: teacher })).json()
  const headers = { 'x-teacher-token': token }
  const created = await request.post('/api/teacher-diagnostic-assignments', { headers, data: {
    classId, studentIds: [pupil.studentId], titleSv: 'Eget subtraktionsexempel', taskIds: ['sub-through-zero-001'] } })
  expect(created.status(), await created.text()).toBe(201)
  await login(page, pupil)
  await page.getByRole('button', { name: 'Eget subtraktionsexempel', exact: true }).click()
  await page.locator('input[data-cell="0:0"]').press('4')
  await page.getByRole('textbox', { name: 'Mitt svar', exact: true }).tap()
  for (const digit of '376') await page.getByRole('button', { name: `Skriv ${digit}`, exact: true }).tap()
  await expect(page.getByText('Alla skickade ändringar är sparade på servern.')).toBeVisible()
  await page.reload()
  await expect(page.getByRole('textbox', { name: 'Mitt svar', exact: true })).toHaveValue('376')
  const day = stockholmDay()
  const params = new URLSearchParams({ resource: 'evidence', classId, from: day, to: day, source: 'screening' })
  const url = `/api/teacher-students/${pupil.studentId}`
  const listed = await (await request.get(`${url}?${params}`, { headers })).json()
  expect(listed.total).toBe(1)
  expect(listed.entries[0].answer).toMatchObject({ studentAnswer: '376', correctAnswer: 224, status: 'incorrect' })
  expect(listed.entries[0]).not.toHaveProperty('detail')
  params.set('ref', listed.entries[0].ref)
  params.set('snapshotRevision', listed.snapshotRevision)
  const response = await request.get(`${url}?${params}`, { headers })
  expect(response.status()).toBe(200)
  const { entry } = await response.json()
  expect(entry.question.operands).toEqual([402, 178])
  expect(entry.detail.snapshot.cells['0:0'].main).toBe('4')
  expect(entry.detail.snapshot.events.some(event => event.type === 'write')).toBe(true)
  expect(entry.reference.observationRevisionId).toMatch(/:r\d+:s\d+$/u)
  params.set('format', 'notebook')
  const exported = await request.get(`${url}?${params}`, { headers })
  expect(exported.status()).toBe(200)
  const original = await exported.json()
  expect(original.snapshotRevision).toBe(listed.snapshotRevision)
  expect(original.notebook.status).toMatchObject({ answerEmpty: false, gridHasContent: true, resultInterpretation: 'not_inferred' })
  expect(original.notebook.text).toContain('r1: 4')
  expect(original.notebook.bounds).toEqual({ firstRow: 0, lastRow: 0, firstColumn: 0, lastColumn: 0 })
  expect(JSON.stringify(original)).not.toMatch(/correctAnswer|facit|events|password/u)
  params.delete('format')
  expect((await (await request.get(`${url}?${params}`, { headers })).json()).entry.detail.snapshot).toEqual(entry.detail.snapshot)
})
